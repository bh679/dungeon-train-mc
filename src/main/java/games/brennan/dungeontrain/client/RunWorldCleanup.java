package games.brennan.dungeontrain.client;

import com.mojang.logging.LogUtils;
import games.brennan.dungeontrain.DungeonTrain;
import games.brennan.dungeontrain.config.ClientDisplayConfig;
import net.minecraft.Util;
import net.minecraft.client.Minecraft;
import net.minecraft.client.gui.screens.TitleScreen;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.nbt.NbtAccounter;
import net.minecraft.nbt.NbtIo;
import net.minecraft.nbt.Tag;
import net.minecraft.world.level.storage.LevelStorageSource;
import net.neoforged.api.distmarker.Dist;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.common.EventBusSubscriber;
import net.neoforged.neoforge.client.event.ScreenEvent;
import org.slf4j.Logger;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.concurrent.atomic.AtomicBoolean;
import java.util.stream.Stream;

/**
 * Removes the save folders of runs that ended in death. Dungeon Train is a new-world-per-run
 * game, so a dead run's world is not worth keeping — left alone, one folder per run piles up
 * into gigabytes.
 *
 * <p>Three ways a dead run's world goes:</p>
 * <ul>
 *   <li>Reboarding from it ({@code DeathScreenLayoutHandler.launchWorldNow}).</li>
 *   <li>Leaving it from the death screen — title or desktop
 *       ({@code DeathScreenLayoutHandler.goToTitleScreen} / {@code quitToDesktop}).</li>
 *   <li>The once-per-launch {@linkplain #sweepAsync sweep} at the first title screen, for every
 *       other way out (window closed on the death screen, a crash after death, a delete that
 *       failed) and for worlds left behind by builds that only deleted on reboard.</li>
 * </ul>
 *
 * <p>Every path is gated the same way: the {@code deleteOnReboard} toggle (the death screen's
 * trash chip) is on, and the folder carries an auto-generated {@code "<prefix><millis>"} name.
 * The sweep additionally needs the saved player to be dead ({@link #isDeadRun}) — a run quit
 * while alive, or one the crash-recovery offer can reopen, is kept.</p>
 */
@EventBusSubscriber(modid = DungeonTrain.MOD_ID, value = Dist.CLIENT)
public final class RunWorldCleanup {

    private static final Logger LOGGER = LogUtils.getLogger();

    /**
     * All auto-generated "<prefix><epoch-millis>" world names that are safe to delete: the death
     * screen's own runs, plus both title-screen New World buttons ({@code DevQuickWorldHandler}:
     * "Dev World " creative, "World " survival). The remainder must be pure digits — a hand-named
     * world like "World of Pain" never matches. Editor worlds ("train editor N") are deliberately
     * absent: they hold authored content.
     */
    private static final List<String> AUTO_WORLD_PREFIXES = List.of(
            "Dungeon Train ", "Dev World ", "World ");

    private static final String LEVEL_DAT = "level.dat";

    private static final AtomicBoolean SWEPT = new AtomicBoolean(false);

    private RunWorldCleanup() {}

    /** True when {@code levelId} is an auto-generated "<prefix><epoch-millis>" name. */
    public static boolean isAutoGeneratedWorldName(String levelId) {
        for (String prefix : AUTO_WORLD_PREFIXES) {
            if (levelId.length() > prefix.length() && levelId.startsWith(prefix)) {
                String rest = levelId.substring(prefix.length());
                if (rest.chars().allMatch(Character::isDigit)) return true;
            }
        }
        return false;
    }

    /**
     * Whether a world's {@code level.dat} root tag records a dead singleplayer player. Vanilla
     * saves a player who leaves on the death screen with 0 health — that's why rejoining such a
     * world reopens the death screen. Anything missing reads as alive, so the world is kept.
     */
    public static boolean isDeadRun(CompoundTag levelDat) {
        CompoundTag data = levelDat.getCompound("Data");
        if (!data.contains("Player", Tag.TAG_COMPOUND)) return false;
        CompoundTag player = data.getCompound("Player");
        if (!player.contains("Health", Tag.TAG_ANY_NUMERIC)) return false;
        return player.getFloat("Health") <= 0.0F;
    }

    /**
     * Delete an already shut-down world's save folder via the vanilla world-list deletion path.
     * Any failure — lingering session lock, IO error, content validation — is logged and
     * swallowed; the next launch's sweep tries again.
     *
     * @return whether the folder was deleted
     */
    public static boolean deleteWorld(Minecraft mc, String levelId) {
        try (LevelStorageSource.LevelStorageAccess access = mc.getLevelSource().createAccess(levelId)) {
            access.deleteLevel();
            LOGGER.info("RunWorldCleanup: deleted world save '{}'", levelId);
            return true;
        } catch (Exception e) {
            LOGGER.warn("RunWorldCleanup: failed to delete world save '{}'; it will remain in the world list.", levelId, e);
            return false;
        }
    }

    /** Run the sweep the first time the title screen opens in this game session. */
    @SubscribeEvent
    public static void onScreenInit(ScreenEvent.Init.Post event) {
        if (!(event.getScreen() instanceof TitleScreen)) return;
        if (!SWEPT.compareAndSet(false, true)) return;
        sweepAsync(Minecraft.getInstance());
    }

    /**
     * Delete every auto-named dead-run world in the saves folder, off the render thread. A world
     * that is somehow open holds its session lock, so {@code createAccess} refuses it and it is
     * skipped.
     */
    public static void sweepAsync(Minecraft mc) {
        if (!ClientDisplayConfig.isDeleteWorldOnReboard()) return;
        Path savesDir = mc.getLevelSource().getBaseDir();
        Util.ioPool().execute(() -> sweep(mc, savesDir));
    }

    private static void sweep(Minecraft mc, Path savesDir) {
        List<Path> candidates;
        try (Stream<Path> entries = Files.list(savesDir)) {
            candidates = entries
                    .filter(Files::isDirectory)
                    .filter(p -> isAutoGeneratedWorldName(p.getFileName().toString()))
                    .toList();
        } catch (IOException e) {
            LOGGER.warn("RunWorldCleanup: could not list saves folder {}; skipping sweep.", savesDir, e);
            return;
        }
        int deleted = 0;
        long bytes = 0;
        for (Path world : candidates) {
            if (!readsAsDeadRun(world)) continue;
            long size = folderSize(world);
            if (deleteWorld(mc, world.getFileName().toString())) {
                deleted++;
                bytes += size;
            }
        }
        if (deleted > 0) {
            LOGGER.info("RunWorldCleanup: swept {} dead-run world(s), freed {} MB.",
                    deleted, bytes / (1024 * 1024));
        }
    }

    private static boolean readsAsDeadRun(Path world) {
        Path levelDat = world.resolve(LEVEL_DAT);
        if (!Files.isRegularFile(levelDat)) return false;
        try {
            return isDeadRun(NbtIo.readCompressed(levelDat, NbtAccounter.unlimitedHeap()));
        } catch (Exception e) {
            LOGGER.warn("RunWorldCleanup: could not read {}; keeping the world.", levelDat, e);
            return false;
        }
    }

    /** Best-effort folder size for the log line; 0 when it can't be measured. */
    private static long folderSize(Path dir) {
        try (Stream<Path> files = Files.walk(dir)) {
            return files.filter(Files::isRegularFile).mapToLong(p -> {
                try {
                    return Files.size(p);
                } catch (IOException e) {
                    return 0L;
                }
            }).sum();
        } catch (IOException e) {
            return 0L;
        }
    }
}
