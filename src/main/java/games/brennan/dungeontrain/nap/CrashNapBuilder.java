package games.brennan.dungeontrain.nap;

import com.mojang.logging.LogUtils;
import games.brennan.dungeontrain.data.SaveFreePlayProbe;
import games.brennan.dungeontrain.difficulty.BoardingProgressData;
import games.brennan.dungeontrain.narrative.NarrativeProgressData;
import games.brennan.dungeontrain.perks.PerksGate;
import games.brennan.dungeontrain.player.PlayerRunState;
import games.brennan.dungeontrain.world.DungeonTrainWorldData;
import games.brennan.dungeontrain.world.RunWorldNames;
import games.brennan.dungeontrain.worldgen.WorldGenCycle;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.nbt.ListTag;
import net.minecraft.nbt.NbtAccounter;
import net.minecraft.nbt.NbtIo;
import net.minecraft.nbt.Tag;
import net.minecraft.util.Mth;
import net.minecraft.world.Difficulty;
import org.slf4j.Logger;

import javax.annotation.Nullable;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.UUID;

/**
 * A crashed run turned into a nap at the title screen, read straight from its save folder: the world
 * is never reopened. The nap then wakes through the ordinary Reboard path ({@link NapWake}) in a new
 * world at the same band and depth, with what the player had on them at the last save.
 *
 * <p>Built from what the save already holds: the player tag vanilla loads them from, the last X they
 * stood at on the train's level ({@link NapGateData}, written every second by {@link NapTrainXTracker}),
 * the world's carriage counter, reverse-slide state, difficulty offset and narrative progress, and the
 * player's advancements and stats files. {@code levelId} is the crashed save, which makes it a napped
 * world: the title-screen sweep deletes it and nothing reopens it.</p>
 *
 * <p>Pure apart from reading files: no Minecraft client or server, so it is pinned in a test.</p>
 */
public final class CrashNapBuilder {

    private static final Logger LOGGER = LogUtils.getLogger();

    private static final String LEVEL_DAT = "level.dat";
    private static final String DATA_DIR = "data";
    private static final String PLAYERDATA_DIR = "playerdata";
    private static final String ADVANCEMENTS_DIR = "advancements";
    private static final String STATS_DIR = "stats";
    private static final String TAG_DATA = "Data";
    private static final String TAG_PLAYER = "Player";
    private static final String TAG_DIFFICULTY = "Difficulty";
    private static final String TAG_SAVED_DATA = "data";
    private static final String TAG_HEALTH = "Health";
    private static final String TAG_POS = "Pos";
    private static final String TAG_ROTATION = "Rotation";
    private static final String TAG_DIMENSION = "Dimension";
    private static final String OVERWORLD = "minecraft:overworld";
    private static final String TAG_TRAVELLED = "travelledCarriageIndex";
    private static final String TAG_REVERSE_ORIGIN_X = "reverseOriginX";
    private static final String TAG_REVERSE_REACH_X = "reverseReachX";
    private static final String TAG_REVERSE_EARNED = "reverseEarned";
    private static final String TAG_REVERSE_SLIDE = "reverseSlide";
    private static final String TAG_DIFFICULTY_OFFSET = "difficultyTravelledOffset";
    private static final String TAG_PERKS_TEST = "perksTest";
    private static final String TAG_STARTS_WITH_TRAIN = "startsWithTrain";

    /**
     * A saved {@code Pos} X beyond this is not a train X: Sable's plot grid sits millions of blocks
     * out (a carriage block's plot position is around 20M), far past any distance ridden.
     */
    static final double MAX_TRAIN_X = 5_000_000.0;

    /** What came of it: a nap and the slot it goes in, or why there is none. */
    public sealed interface Result permits Built, Refused {}

    public record Built(NapSnapshot nap, String slot) implements Result {}

    public record Refused(String why) implements Result {}

    private CrashNapBuilder() {}

    /**
     * The nap for {@code owner}'s crashed run in {@code levelDir}, saved as {@code levelId}.
     *
     * @param cycle the band layout to record the train's place in; null records none (it wakes by X)
     */
    public static Result build(Path levelDir, String levelId, UUID owner, String modVersion,
                               @Nullable WorldGenCycle cycle, long nowMs) {
        if (!RunWorldNames.isAutoGenerated(levelId)) return new Refused("not a run world");
        CompoundTag levelData = levelData(levelDir);
        if (levelData == null) return new Refused("level.dat unreadable");
        CompoundTag world = savedData(levelDir, DungeonTrainWorldData.NAME);
        if (world.contains(TAG_STARTS_WITH_TRAIN) && !world.getBoolean(TAG_STARTS_WITH_TRAIN)) {
            return new Refused("not a train world");
        }
        CompoundTag player = playerTag(levelDir, levelData, owner);
        if (player == null) return new Refused("no saved player");
        if (player.getFloat(TAG_HEALTH) <= 0f) return new Refused("player was dead");
        NapGateData.Entry gate = gateEntry(levelDir, owner);
        double x = trainX(gate, player);
        if (Double.isNaN(x)) return new Refused("no train X");

        boolean freePlay = SaveFreePlayProbe.wasFreePlay(levelDir, owner);
        boolean testWorld = world.getBoolean(TAG_PERKS_TEST);
        Difficulty difficulty = Difficulty.byId(levelData.getByte(TAG_DIFFICULTY));
        String slot = NapSlot.keyFor(freePlay, difficulty, testWorld);
        String profile = testWorld ? PerksGate.TEST_PROFILE : difficulty.getKey();

        NapSnapshot nap = new NapSnapshot(UUID.randomUUID(), nowMs, modVersion, levelId, player, x,
            (int) Math.floor(x / NapService.BLOCKS_PER_CARRIAGE), "", facingAlongX(player),
            savedData(levelDir, BoardingProgressData.NAME).getInt(TAG_TRAVELLED), freePlay, profile,
            readText(levelDir.resolve(ADVANCEMENTS_DIR).resolve(owner + ".json")),
            readText(levelDir.resolve(STATS_DIR).resolve(owner + ".json")),
            NarrativeProgressData.exportFrom(savedData(levelDir, NarrativeProgressData.NAME), owner),
            // Not one more: a crash is not a nap the player took.
            PlayerRunState.extrasWithNapSaves(gate.napSaves()),
            world.getInt(TAG_DIFFICULTY_OFFSET)).withPlace(placeAt(cycle, x, world));
        return new Built(nap, slot);
    }

    /**
     * The X the train was at: the last one recorded on the train's level, else the saved position when
     * that is in the overworld and not out in the plot grid, else NaN.
     */
    static double trainX(NapGateData.Entry gate, CompoundTag player) {
        if (Double.isFinite(gate.lastTrainX())) return gate.lastTrainX();
        String dim = player.contains(TAG_DIMENSION) ? player.getString(TAG_DIMENSION) : OVERWORLD;
        ListTag pos = player.getList(TAG_POS, Tag.TAG_DOUBLE);
        if (!OVERWORLD.equals(dim) || pos.size() != 3) return Double.NaN;
        double x = pos.getDouble(0);
        return Double.isFinite(x) && Math.abs(x) <= MAX_TRAIN_X ? x : Double.NaN;
    }

    /**
     * The train's band place at {@code x}, as {@code NapService.placeAt} records it. Only ahead of the
     * origin: behind it a band's X depends on the live reverse slide, which only the running world has,
     * so a reversed place is left out and the nap wakes by X alone.
     */
    static NapSnapshot.Place placeAt(@Nullable WorldGenCycle cycle, double x, CompoundTag world) {
        if (cycle == null) return null;
        try {
            WorldGenCycle.BandPosition pos = cycle.bandPosition(Mth.floor(x));
            if (pos == null || pos.reversed()) return null;
            return new NapSnapshot.Place(pos, longOr(world, TAG_REVERSE_ORIGIN_X, Long.MAX_VALUE),
                longOr(world, TAG_REVERSE_REACH_X, Long.MAX_VALUE), Math.max(0L, world.getLong(TAG_REVERSE_EARNED)),
                Math.max(0L, world.getLong(TAG_REVERSE_SLIDE)));
        } catch (RuntimeException e) {
            LOGGER.warn("[DungeonTrain] Crash nap: band place not recorded at x={}; it will wake by X", x, e);
            return null;
        }
    }

    /** +1 facing +X, -1 facing -X, from the saved yaw (as {@code NapService#facingAlongX}). */
    static int facingAlongX(CompoundTag player) {
        ListTag rot = player.getList(TAG_ROTATION, Tag.TAG_FLOAT);
        float yaw = rot.isEmpty() ? 0f : rot.getFloat(0);
        return -Mth.sin(yaw * Mth.DEG_TO_RAD) >= 0 ? 1 : -1;
    }

    private static CompoundTag levelData(Path levelDir) {
        CompoundTag root = read(levelDir.resolve(LEVEL_DAT));
        if (root == null || !root.contains(TAG_DATA, Tag.TAG_COMPOUND)) return null;
        return root.getCompound(TAG_DATA);
    }

    /** The tag vanilla loads a singleplayer owner from ({@code level.dat}), else their playerdata file. */
    private static CompoundTag playerTag(Path levelDir, CompoundTag levelData, UUID owner) {
        if (levelData.contains(TAG_PLAYER, Tag.TAG_COMPOUND)) return levelData.getCompound(TAG_PLAYER);
        return read(levelDir.resolve(PLAYERDATA_DIR).resolve(owner + ".dat"));
    }

    private static NapGateData.Entry gateEntry(Path levelDir, UUID owner) {
        CompoundTag gates = savedData(levelDir, NapGateData.NAME);
        String key = owner.toString();
        return gates.contains(key, Tag.TAG_COMPOUND) ? NapGateData.readEntry(gates.getCompound(key)) : NapGateData.Entry.EMPTY;
    }

    /** The {@code data} compound of {@code data/<name>.dat}, empty when missing or unreadable. */
    private static CompoundTag savedData(Path levelDir, String name) {
        CompoundTag root = read(levelDir.resolve(DATA_DIR).resolve(name + ".dat"));
        if (root == null || !root.contains(TAG_SAVED_DATA, Tag.TAG_COMPOUND)) return new CompoundTag();
        return root.getCompound(TAG_SAVED_DATA);
    }

    private static long longOr(CompoundTag t, String key, long fallback) {
        return t.contains(key) ? t.getLong(key) : fallback;
    }

    private static String readText(Path file) {
        if (!Files.isRegularFile(file)) return "";
        try {
            return Files.readString(file, StandardCharsets.UTF_8);
        } catch (IOException | RuntimeException e) {
            LOGGER.warn("[DungeonTrain] Crash nap: could not read {}; not carried", file, e);
            return "";
        }
    }

    private static CompoundTag read(Path file) {
        if (!Files.isRegularFile(file)) return null;
        try {
            return NbtIo.readCompressed(file, NbtAccounter.unlimitedHeap());
        } catch (IOException | RuntimeException e) {
            LOGGER.warn("[DungeonTrain] Crash nap: couldn't read {}: {}", file, e.toString());
            return null;
        }
    }
}
